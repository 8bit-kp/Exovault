import type { ExposedDataType, ExposureSourceType, RemediationState } from "./exposure";

/**
 * Remediation (spec 7.7, 13.6). User-driven, separate from detection state.
 * Transitions are explicit; anything not listed is rejected.
 *
 *   open ──▶ in_progress ──▶ remediated
 *     │          │    ▲            │
 *     ├──────────┼────┘ (reopen)   │
 *     ▼          ▼                 ▼
 *   dismissed ◀──────────── (reopen to open)
 */
const EDGES: Record<RemediationState, readonly RemediationState[]> = {
  open: ["in_progress", "remediated", "dismissed"],
  in_progress: ["open", "remediated", "dismissed"],
  remediated: ["in_progress", "open"],
  dismissed: ["open"],
};

export function canTransitionRemediation(from: RemediationState, to: RemediationState): boolean {
  return EDGES[from].includes(to);
}

