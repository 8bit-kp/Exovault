const PASSWORDS: readonly ExposedDataType[] = ["password_plaintext", "password_hash", "auth_token"];

/**
 * The checklist for one exposure, built from what was actually exposed. Pure
 * and deterministic: the keys are stable, so saved progress survives reloads.
 */
export function getRemediationChecklist(exposure: {
  dataTypes: readonly ExposedDataType[];
  sourceType: ExposureSourceType;
}): ChecklistItem[] {
  const has = (...types: ExposedDataType[]) => exposure.dataTypes.some((t) => types.includes(t));
  const keys: ChecklistKey[] = [];
  if (exposure.sourceType === "stealer_log") keys.push("clean-device");
  if (has(...PASSWORDS) || exposure.sourceType === "stealer_log") {
    keys.push("change-password", "update-reused-passwords", "enable-mfa");
  }
  if (has("security_qa")) keys.push("change-security-questions");
  keys.push("review-account-activity");
  if (has("financial")) keys.push("watch-financial-statements");
  if (has("government_id") || (has("date_of_birth") && has("physical_address")))
    keys.push("protect-identity");
  if (has("phone")) keys.push("secure-phone-number");
  if (!has(...PASSWORDS)) keys.push("watch-phishing");
  return keys.map((key) => ({ key, ...ITEMS[key] }));
}

/**
 * Remediation state implied by checklist progress (D-031):
 * all done → remediated; some done → in_progress; none → open.
 * A dismissed exposure stays dismissed until the user reopens it.
 */
export function stateFromChecklist(current: RemediationState, done: number, total: number): RemediationState {
  if (current === "dismissed") return "dismissed";
  if (total > 0 && done >= total) return "remediated";
  if (done > 0) return "in_progress";
  return current === "remediated" || current === "in_progress" ? "open" : current;
}

